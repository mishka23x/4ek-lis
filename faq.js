'use strict';

(() => {
  const block = document.getElementById('faqTemplate');
  if (block) {
    try {
      const faq = JSON.parse(block.textContent);
      const items = Array.isArray(faq.items) ? faq.items : [];
      for (const item of items) {
        const question = String(item && item.q || '');
        if (question.includes('Заполненный мной чек-лист виден всем')) {
          item.a = '— Сам чек-лист, введённые ссылки и тексты заданий никому не публикуются и остаются в вашем браузере. Если владелец явно включает итоговую статистику сезона, по кнопке отправляется расширенный, но обезличенно-псевдонимный статистический снимок: ник, случайный ID браузера, количество выполненных заданий, агрегаты ссылок без самих URL, избранное, цели, статистика по ID категорий/заданий и агрегированная активность по дням. Тексты постов, сами URL, содержимое backup-файла и полный localStorage не отправляются.';
        }
        if (question.includes('ноутбуке') && question.includes('мобильного')) {
          item.a = '— Прогресс и случайный participantId хранятся локально в конкретном браузере. Поэтому другой браузер или устройство автоматически не получает ваши галочки и ссылки. Для переноса прогресса используйте экспорт/восстановление JSON-файла.';
        }
      }
      items.push({
        q: 'Какие данные могут отправляться в итоговую статистику сезона?',
        a: '— Только после явного включения владельцем и нажатия кнопки итогов: техническая версия схемы/шаблона, случайные submissionId и participantId, домен страницы, ник, общие показатели выполнения, количество корректных/уникальных/дублированных/ошибочных ссылок без самих адресов, количество избранных заданий, агрегаты по ID категорий и заданий, цели на сезон и суммарная активность по дням. Не отправляются тексты постов, URL публикаций, текст заданий/категорий в payload, история браузера, содержимое backup или произвольные данные localStorage.'
      });
      faq.items = items;
      block.textContent = JSON.stringify(faq);
    } catch (_) {
      // If FAQ data cannot be updated, the original renderer still receives it unchanged.
    }
  }

  const core = document.createElement('script');
  core.src = 'faq-core.js';
  document.head.appendChild(core);
})();
